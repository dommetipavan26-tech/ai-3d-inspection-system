"""
backend/esp32_simulator.py
==========================
STEP 1 -- 16-pin AI-Thinker ESP32-CAM (OV2640) photo capture.

Two capture paths feed the very same ingestion endpoint:

  1. *Physical* nodes: the Arduino/PlatformIO firmware in
     ``esp32_cam_ov2640/esp32_cam_inspection.ino`` does an HTTPS multipart
     POST of the JPEG to ``/api/esp32/upload`` and long-polls
     ``/api/esp32/command`` every 3 s.
  2. *This module*: a physically-based OV2640 renderer that reproduces what
     the 8-node orbital rig actually sees -- a cast-in-place reinforced
     concrete pier carrying four real structural defects (diagonal shear
     crack, rebar corrosion, spalling, efflorescence) -- so the whole
     downstream chain (COLMAP, AI detector, ray back-projection) can be
     exercised, calibrated and regression-tested without hardware.

Rendering pipeline
------------------
    procedural texture atlas (cylindrical unwrap, ~0.5 mm/texel)
        -> per-pixel pinhole ray casting (analytic ray/cylinder + ray/ground)
        -> Lambert + hemispheric ambient + Blinn-Phong shading
        -> OV2640 sensor model (vignetting, fixed-pattern noise, chroma
           noise, lens softness, JPEG q88)

Because every defect is anchored in *world* coordinates on the pier surface,
the eight orbital frames exhibit true multi-view parallax -- which is exactly
what makes the COLMAP solve and the 2D->3D ray back-projection in step 4
physically meaningful.
"""

