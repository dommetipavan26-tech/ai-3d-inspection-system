SUN_DIR = np.array([0.46, 0.79, 0.41], dtype=np.float32)
SUN_DIR /= np.linalg.norm(SUN_DIR)

APRON_M = 30.0        # ground apron extent rendered around the pier


@dataclass
class RenderedFrame:
    image_bgr: np.ndarray
    depth_m: np.ndarray
    labels: np.ndarray
    view_index: int
    K: np.ndarray
    R: np.ndarray
    t: np.ndarray


class PierSceneRenderer:
    """
    Analytic ray-cast renderer for the pier + ground apron scene.

    For every sensor pixel the pinhole ray is intersected analytically with
    (a) the finite cylinder that is the pier and (b) the ground apron; the
    nearest positive root wins.  Surface albedo comes from the procedural
    texture atlas, then Lambert + hemispheric ambient + Blinn-Phong specular
    shading is applied, followed by an OV2640 sensor model.
    """

    def __init__(self, material: Optional[PierMaterial] = None, supersample: int = 1):
        self.material = material or PierMaterial().build()
        self.supersample = max(1, int(supersample))
        self.ground = self._build_ground()

    # ---------------------------------------------------------- ground cache
    @staticmethod
    def _build_ground(res: int = 1024) -> Dict[str, np.ndarray]:
        """Pre-computed concrete apron texture (albedo + micro detail)."""
        lin = np.linspace(-APRON_M / 2, APRON_M / 2, res, dtype=np.float32)
        gx, gz = np.meshgrid(lin, lin)
        tex = noise2d((res, res), 26.0, 26.0, 4, 9091, wrap_x=False)
        gravel = noise2d((res, res), 300.0, 300.0, 1, 9092, wrap_x=False)
        col = 0.30 + 0.12 * (tex - 0.5) + 0.07 * (gravel - 0.5)
        joint_d = np.abs(((gx + 1.2) % 2.4) - 1.2)
        joint_d2 = np.abs(((gz + 1.2) % 2.4) - 1.2)
        col *= 1.0 - 0.35 * (1.0 - smoothstep(0.0, 0.035, np.minimum(joint_d, joint_d2)))
        col *= 1.0 - 0.20 * np.clip((np.sqrt(gx * gx + gz * gz) - 6.0) / 4.0, 0.0, 1.0)
        col *= 1.0 - 0.35 * np.exp(-np.clip(np.sqrt(gx * gx + gz * gz)
                                            - C.COLUMN_RADIUS_M, 0, 1) / 0.25)
        # distance fade: the apron dissolves into haze before the texture
        # reaches its clamped edge (kills the radial streak artefact)
        fog = smoothstep(14.0, 28.0, np.sqrt(gx * gx + gz * gz))
        return {"extent": APRON_M, "orig": -APRON_M / 2, "res": res,
                "col": np.clip(col, 0.02, 1.0).astype(np.float32),
                "fog": fog.astype(np.float32)}

    # -------------------------------------------------------------- geometry
    @staticmethod
    def _ray_directions(view: C.CameraView, width: int, height: int, ss: int):
        """World-space unit ray directions + the camera centre for a view."""
        xs = ((np.arange(width * ss) + 0.5) / ss - 0.5).astype(np.float32)
        ys = ((np.arange(height * ss) + 0.5) / ss - 0.5).astype(np.float32)
        u, v = np.meshgrid(xs, ys)
        fx, fy = float(view.K[0, 0]), float(view.K[1, 1])
        cx, cy = float(view.K[0, 2]), float(view.K[1, 2])
        d_cam = np.stack([(u - cx) / fx, (v - cy) / fy, np.ones_like(u)], axis=-1)
        d_world = d_cam.reshape(-1, 3) @ view.R.astype(np.float32)
        d_world /= np.linalg.norm(d_world, axis=1, keepdims=True)
        return d_world.astype(np.float32), view.center.astype(np.float32)

    @staticmethod
    def _intersect(d_world, centre, radius, height):
        """Nearest positive hit on the pier and the ground apron, per ray."""
        dx, dy, dz = d_world[:, 0], d_world[:, 1], d_world[:, 2]
        ox, oy, oz = float(centre[0]), float(centre[1]), float(centre[2])

        a = dx * dx + dz * dz
        b = 2.0 * (ox * dx + oz * dz)
        c = ox * ox + oz * oz - radius * radius
        disc = b * b - 4.0 * a * c
        ok = (disc > 0) & (a > 1e-12)
        sq = np.sqrt(np.where(ok, disc, 0.0))
        a_safe = np.where(a > 1e-12, a, 1.0)
        t1 = np.where(ok, (-b - sq) / (2.0 * a_safe), np.inf)
        t2 = np.where(ok, (-b + sq) / (2.0 * a_safe), np.inf)
        with np.errstate(invalid="ignore"):
            y1 = oy + t1 * dy
            y2 = oy + t2 * dy
        t1 = np.where((t1 > 1e-3) & (y1 >= 0.0) & (y1 <= height), t1, np.inf)
        t2 = np.where((t2 > 1e-3) & (y2 >= 0.0) & (y2 <= height), t2, np.inf)
        t_cyl = np.minimum(t1, t2).astype(np.float32)

        with np.errstate(divide="ignore", invalid="ignore"):
            t_gnd = np.where(np.abs(dy) > 1e-9, -oy / dy, np.inf)
        t_gnd = np.where(t_gnd > 1e-3, t_gnd, np.inf).astype(np.float32)
        return t_cyl, t_gnd

    # -------------------------------------------------------------- shading
    def render(self, view: C.CameraView, seed: Optional[int] = None) -> RenderedFrame:
        W, H = view.width, view.height
        ss = self.supersample
        rng = np.random.default_rng(view.index * 7919 + (seed if seed is not None else 0))

        d_world, centre = self._ray_directions(view, W, H, ss)
        t_cyl, t_gnd = self._intersect(d_world, centre, C.COLUMN_RADIUS_M, C.COLUMN_HEIGHT_M)
        t_hit = np.minimum(t_cyl, t_gnd)

        on_cyl = np.isfinite(t_cyl) & (t_cyl <= t_gnd)
        on_gnd = (~on_cyl) & np.isfinite(t_gnd)
        sky = ~on_cyl & ~on_gnd

        colour = np.zeros((d_world.shape[0], 3), dtype=np.float32)

        # --- sky: zenith gradient + sun glow + horizon haze ------------------
        up = np.clip(d_world[:, 1], -1.0, 1.0)
        sky_base = np.stack([0.42 + 0.30 * np.clip(up + 0.25, 0, 1),
                             0.55 + 0.32 * np.clip(up + 0.20, 0, 1),
                             0.78 + 0.20 * np.clip(up + 0.10, 0, 1)], axis=-1)
        sun_dot = np.clip(d_world @ SUN_DIR, 0.0, 1.0) ** 24.0
        sky_base += np.array([0.55, 0.48, 0.34], dtype=np.float32) * sun_dot[:, None]
        haze = np.exp(-np.clip(np.where(np.isfinite(t_hit), t_hit, 60.0), 0, 400) / 140.0)
        sky_base = sky_base * haze[:, None] + np.array([0.72, 0.76, 0.80], dtype=np.float32) * (1 - haze)[:, None]
        colour[sky] = sky_base[sky]

        # --- ground apron ----------------------------------------------------
        if on_gnd.any():
            idx = np.flatnonzero(on_gnd)
            px = centre[0] + t_hit[idx] * d_world[idx, 0]
            pz = centre[2] + t_hit[idx] * d_world[idx, 2]
            g = self.ground
            gx_px = (px - g["orig"]) / g["extent"] * (g["res"] - 1)
            gz_px = (pz - g["orig"]) / g["extent"] * (g["res"] - 1)
            gcol = bilinear_sample(g["col"], gx_px, gz_px)

            # hard shadow cast by the pier
            sun_a = SUN_DIR[0] ** 2 + SUN_DIR[2] ** 2
            sun_b = 2.0 * (px * SUN_DIR[0] + pz * SUN_DIR[2])
            sun_c = px * px + pz * pz - C.COLUMN_RADIUS_M ** 2
            sun_disc = sun_b * sun_b - 4.0 * sun_a * sun_c
            in_shadow = (sun_disc > 0) & (sun_a > 1e-9)
            ts = np.where(in_shadow, (-sun_b - np.sqrt(np.maximum(sun_disc, 0.0))) / (2.0 * sun_a), 0.0)
            ys = ts * SUN_DIR[1]
            in_shadow = in_shadow & (ts > 0) & (ys >= 0) & (ys <= C.COLUMN_HEIGHT_M)
            gcol = np.where(in_shadow, gcol * 0.52, gcol)
            fog = bilinear_sample(g["fog"], gx_px, gz_px)
            haze_rgb = np.array([0.72, 0.76, 0.80], dtype=np.float32)
            gcol = np.clip(gcol, 0.02, 1.0)
            base = np.stack([gcol * 1.02, gcol, gcol * 0.95], axis=-1)
            colour[idx] = base * (1.0 - fog[:, None]) + haze_rgb * fog[:, None]

        # --- pier surface -----------------------------------------------------
        if on_cyl.any():
            idx = np.flatnonzero(on_cyl)
            hx = centre[0] + t_cyl[idx] * d_world[idx, 0]
            hy = centre[1] + t_cyl[idx] * d_world[idx, 1]
            hz = centre[2] + t_cyl[idx] * d_world[idx, 2]
            th = np.arctan2(hx, hz)
            nx, nz = hx / C.COLUMN_RADIUS_M, hz / C.COLUMN_RADIUS_M

            A = self.material.albedo
            u_px = ((th + math.pi) / (2.0 * math.pi)) * A.shape[1] - 0.5
            v_px = (1.0 - hy / C.COLUMN_HEIGHT_M) * A.shape[0] - 0.5

            alb = bilinear_sample(A, u_px, v_px)
            rough = bilinear_sample(self.material.roughness, u_px, v_px)
            metal = bilinear_sample(self.material.metal, u_px, v_px)

            ndl = nx * SUN_DIR[0] + nz * SUN_DIR[2]        # cylinder normal is horizontal
            wrapped = np.clip((ndl + 0.34) / 1.34, 0.0, 1.0)
            shadow_edge = 1.0 - 0.55 * smoothstep(0.08, -0.18, ndl)
            # key light + hemispheric sky fill + ground bounce
            # key light + hemispheric sky fill + ground bounce
            diffuse = (0.50 * wrapped + 0.34 + 0.30 * wrapped * shadow_edge).astype(np.float32)

            view_dir = -d_world[idx]
            half = view_dir + SUN_DIR.reshape(1, 3)
            half /= np.linalg.norm(half, axis=1, keepdims=True)
            ndh = np.clip(nx * half[:, 0] + nz * half[:, 2], 0.0, 1.0)
            spec = (ndh ** (6.0 + 90.0 * np.clip(1.0 - metal, 0, 1))
                    * (0.045 + 0.55 * metal) * (1.0 - 0.6 * rough)).astype(np.float32)

            shade = alb * diffuse[:, None] * 1.22 + spec[:, None]
            ao = (0.78 + 0.22 * np.clip(hy / 0.45, 0.0, 1.0)) * \
                 (0.86 + 0.14 * np.clip((C.COLUMN_HEIGHT_M - hy) / 0.25, 0.0, 1.0))
            shade *= ao[:, None].astype(np.float32)
            colour[idx] = np.clip(shade, 0.0, 1.35)

        # --- downsample from the supersampled buffer --------------------------
        img = colour.reshape(H * ss, W * ss, 3)
        if ss > 1:
            img = cv2.resize(img, (W, H), interpolation=cv2.INTER_AREA)

        t_img = np.where(np.isfinite(t_hit), t_hit, 0.0).reshape(H * ss, W * ss)
        if ss > 1:
            t_img = cv2.resize(t_img, (W, H), interpolation=cv2.INTER_AREA)
        depth = np.where(t_img > 0, t_img, 0.0).astype(np.float32)

        img = self._apply_sensor(img, rng)
        image_bgr = (np.clip(img * 255.0, 0, 255).astype(np.uint8))[..., ::-1].copy()

        labels = self._render_labels(view, W, H)
        return RenderedFrame(image_bgr=image_bgr, depth_m=depth, labels=labels,
                             view_index=view.index, K=view.K.copy(),
                             R=view.R.copy(), t=view.t.copy())

    # ------------------------------------------------------------- labels
    def _render_labels(self, view: C.CameraView, W: int, H: int) -> np.ndarray:
        """Pixel-accurate ground-truth class map for detector scoring."""
        d_world, centre = self._ray_directions(view, W, H, 1)
        t_cyl, t_gnd = self._intersect(d_world, centre, C.COLUMN_RADIUS_M, C.COLUMN_HEIGHT_M)
        on_cyl = np.isfinite(t_cyl) & (t_cyl <= t_gnd)
        labels = np.zeros(W * H, dtype=np.uint8)
        if on_cyl.any():
            idx = np.flatnonzero(on_cyl)
            px = centre[0] + t_cyl[idx] * d_world[idx, 0]
            py = centre[1] + t_cyl[idx] * d_world[idx, 1]
            pz = centre[2] + t_cyl[idx] * d_world[idx, 2]
            th = np.arctan2(px, pz)
            xi = np.clip(np.round(((th + math.pi) / (2.0 * math.pi)) * ATLAS_W - 0.5).astype(np.int32),
                         0, ATLAS_W - 1)
            yi = np.clip(np.round((1.0 - py / C.COLUMN_HEIGHT_M) * ATLAS_H - 0.5).astype(np.int32),
                         0, ATLAS_H - 1)
            labels[idx] = self.material.labels[yi, xi]
        return labels.reshape(H, W)

    # ------------------------------------------------------------ sensor sim
    def _apply_sensor(self, img, rng):
        H, W = img.shape[:2]
        yy, xx = np.mgrid[0:H, 0:W]
        cx, cy = (W - 1) / 2.0, (H - 1) / 2.0
        r2 = (((xx - cx) / cx) ** 2 + ((yy - cy) / cy) ** 2).astype(np.float32)

        # exposure + white-balance drift between nodes
        img = img * float(rng.uniform(0.95, 1.06)) * rng.uniform(0.98, 1.02, size=3).astype(np.float32).reshape(1, 1, 3)

        # lens vignetting (~-0.35 EV in the corners) + optical softness
        img *= (1.0 - 0.19 * r2 ** 1.7)[..., None]
        img = cv2.GaussianBlur(img, (0, 0), 0.55)
        img = cv2.GaussianBlur(img, (0, 0), 0.40)

        # tone response of the OV2640 JPEG pipeline
        img = np.clip(img, 0.0, 1.0) ** 0.87

        # fixed-pattern noise + per-channel read noise + chroma blotching
        fpn = cv2.GaussianBlur(rng.normal(0.0, 0.006, size=(H, W)).astype(np.float32), (0, 0), 1.1)[..., None]
        read = rng.normal(0.0, 0.010, size=(H, W, 3)).astype(np.float32)
        chroma = cv2.GaussianBlur(rng.normal(0.0, 0.012, size=(H, W, 3)).astype(np.float32), (0, 0), 2.0)
        img = img + fpn + read + chroma

        # dust specks on the sensor window
        for _ in range(int(rng.integers(3, 8))):
            dxx, dyy = int(rng.integers(0, W)), int(rng.integers(0, H))
            cv2.circle(img, (dxx, dyy), int(rng.integers(1, 4)),
                       tuple(float(v) for v in rng.uniform(0.5, 0.8, 3)), -1, lineType=cv2.LINE_AA)
        return np.clip(img, 0.0, 1.0)


