class CommandBus:
    """
    Server-side command queue backing ``GET /api/esp32/command``.

    The firmware polls every 3 s; each poll pops one queued command
    (``capture``, ``flash``, ``set_interval``, ``reboot``, ``status``) and
    returns ``idle`` when the queue is empty.
    """

    def __init__(self, maxlen: int = 64):
        self.queue: Deque[dict] = deque(maxlen=maxlen)
        self.history: Deque[dict] = deque(maxlen=128)

    def push(self, command: str, **params) -> dict:
        item = {"id": str(uuid.uuid4())[:8], "command": command, "params": params,
                "issued": datetime.now(timezone.utc).isoformat(timespec="seconds")}
        self.queue.append(item)
        self.history.appendleft(item)
        return item

    def pop(self, device_id: Optional[str] = None) -> dict:
        if self.queue:
            item = dict(self.queue.popleft())
            item["target"] = device_id or "broadcast"
            return item
        return {"id": "idle", "command": "idle", "params": {"sleep_ms": 3000},
                "target": device_id or "broadcast",
                "issued": datetime.now(timezone.utc).isoformat(timespec="seconds")}

    def status(self):
        return {"pending": len(self.queue), "queue": list(self.queue),
                "recent": list(self.history)[:10]}


