# High level simulator / Step-1 orchestrator
# ==========================================================================


class ESP32CamSimulator:
    """
    STEP 1 orchestrator: renders the 8-view orbital sweep, persists the JPEGs
    plus ground-truth label maps, and exposes the same "device fleet" view
    that the real firmware-backed endpoints report.
    """

    def __init__(self, material: Optional[PierMaterial] = None,
                 supersample: int = 1, compress: int = C.JPEG_QUALITY):
        self.material = material or PierMaterial().build()
        self.renderer = PierSceneRenderer(self.material, supersample=supersample)
        self.compress = compress
        self.views = C.camera_rig()
        self.devices: List[ESP32Device] = [
            ESP32Device(device_id=v.device_id, view_index=v.index, label=v.label,
                        ip=f"10.20.3.{10 + v.index}", rssi_dbm=v.rssi_dbm,
                        battery_v=round(3.9 + 0.02 * (v.index % 5), 2),
                        uploads=(v.index * 3) % 7)
            for v in self.views
        ]
        self.commands = CommandBus()
        self.last_capture: Optional[dict] = None
        self.capture_times: List[float] = []

    # ------------------------------------------------------------ capture
    def capture_view(self, index: int, save: bool = True) -> dict:
        view = self.views[index]
        dev = self.devices[index]
        dev.status = "FLASH/CAPTURE"
        t0 = time.time()
        frame = self.renderer.render(view)

        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        jpg_path = C.CAPTURE_DIR / view.image_name
        ok, buf = cv2.imencode(".jpg", frame.image_bgr,
                               [int(cv2.IMWRITE_JPEG_QUALITY), self.compress])
        data = buf.tobytes() if ok else b""
        if save and ok:
            jpg_path.write_bytes(data)
            cv2.imwrite(str(C.GT_DIR / f"gt_overlay_view_{index + 1:02d}.jpg"),
                        self._label_overlay(frame.image_bgr, frame.labels),
                        [int(cv2.IMWRITE_JPEG_QUALITY), 82])
            np.save(C.GT_DIR / f"labels_view_{index + 1:02d}.npy", frame.labels)
            np.save(C.CAPTURE_DIR / f"depth_view_{index + 1:02d}.npy", frame.depth_m)

        dev.status = "IDLE"
        dev.uploads += 1
        dev.last_upload = stamp
        dev.last_seen = time.time()

        labels = frame.labels
        counts = {c: int((labels == i + 1).sum()) for i, c in enumerate(C.DEFECT_CLASSES)}
        dt = time.time() - t0
        self.capture_times.append(dt)
        return {
            "view": view.to_dict(), "filename": view.image_name, "bytes": len(data),
            "path": str(jpg_path), "captured_at": stamp, "render_s": round(dt, 2),
            "labels": counts, "defect_pixels": int(sum(counts.values())),
        }

    def capture_sweep(self, save: bool = True) -> dict:
        """The full 8-node orbital sweep (what the dashboard button triggers)."""
        t0 = time.time()
        views = [self.capture_view(i, save=save) for i in range(C.N_VIEWS)]
        self.last_capture = {
            "started": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "duration_s": round(time.time() - t0, 2), "n_views": len(views),
            "views": views, "rig": C.scene_summary()["rig"],
        }
        return self.last_capture

    # ------------------------------------------------------------- helpers
    @staticmethod
    def _label_overlay(image_bgr: np.ndarray, labels: np.ndarray) -> np.ndarray:
        out = image_bgr.astype(np.float32)
        for i, cls in enumerate(C.DEFECT_CLASSES):
            m = (labels == (i + 1)).astype(np.uint8)
            if not m.any():
                continue
            bgr = np.array(C.DEFECT_META[cls]["rgb"], dtype=np.float32)[::-1]
            sel = m.astype(bool)
            out[sel] = out[sel] * 0.55 + bgr * 0.45
            cont, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            cv2.drawContours(out, cont, -1, tuple(float(v) for v in bgr), 3, cv2.LINE_AA)
        return np.clip(out, 0, 255).astype(np.uint8)

    def fleet_status(self) -> dict:
        return {
            "n_nodes": len(self.devices),
            "online": sum(1 for d in self.devices if time.time() - d.last_seen < 3600),
            "devices": [d.to_dict() for d in self.devices],
            "commands": self.commands.status(),
            "avg_render_s": (round(float(np.mean(self.capture_times[-8:])), 2)
                             if self.capture_times else None),
        }

    def ingest_upload(self, filename: str, data: bytes, view_index: Optional[int] = None,
                      device_id: str = "") -> dict:
        """
        Ingest a JPEG arriving from a real ESP32-CAM (HTTPS multipart POST) or
        from the browser upload widget.  Files land in ``data/uploads`` and, if
        a view index is known, are promoted into the live capture set.
        """
        safe = Path(filename or "").name or f"esp32_{int(time.time())}.jpg"
        dest = C.UPLOAD_DIR / safe
        if dest.exists():
            dest = C.UPLOAD_DIR / f"{dest.stem}_{int(time.time())}{dest.suffix}"
        dest.write_bytes(data)

        arr = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)
        h, w = (arr.shape[:2] if arr is not None else (0, 0))

        promoted = None
        if arr is not None and view_index is None:
            digits = "".join(ch for ch in safe if ch.isdigit())
            if digits:
                cand = int(digits[:2]) - 1
                view_index = cand if 0 <= cand < C.N_VIEWS else None
        if arr is not None and view_index is not None and 0 <= view_index < C.N_VIEWS:
            cv2.imwrite(str(C.CAPTURE_DIR / self.views[view_index].image_name), arr,
                        [int(cv2.IMWRITE_JPEG_QUALITY), 95])
            promoted = str(C.CAPTURE_DIR / self.views[view_index].image_name)
            dev = self.devices[view_index]
            dev.last_upload = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            dev.uploads += 1
            dev.last_seen = time.time()

        return {
            "ok": arr is not None, "filename": safe, "stored": str(dest),
            "promoted": promoted, "view_index": view_index,
            "device_id": device_id or (self.devices[view_index].device_id
                                       if view_index is not None else ""),
            "resolution": [w, h], "bytes": len(data),
            "received_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }

    # ------------------------------------------------------- texture atlas
    def save_texture_atlas(self, path: Optional[Path] = None) -> str:
        """Export the cylindrical unwrap for the report / QA."""
        path = Path(path) if path else (C.ANALYSIS_DIR / "pier_texture_atlas.jpg")
        rgb = np.clip(self.material.albedo[..., ::-1] * 255, 0, 255).astype(np.uint8)
        cv2.imwrite(str(path), cv2.resize(rgb, (1536, 768), interpolation=cv2.INTER_AREA),
                    [int(cv2.IMWRITE_JPEG_QUALITY), 88])
        return str(path)

    def label_stats(self) -> dict:
        lab = self.material.labels
        total = lab.size
        px_m2 = (SURF_W / ATLAS_W) * (SURF_H / ATLAS_H)
        out = {}
        for i, cls in enumerate(C.DEFECT_CLASSES):
            n = int((lab == i + 1).sum())
            out[cls] = {"texels": n, "fraction_pct": round(100.0 * n / total, 4),
                        "surface_area_cm2": round(n * px_m2 * 1e4, 2)}
        return out
