# ==========================================================================
# Fast procedural noise
# ==========================================================================
# Value noise is generated by drawing a small random lattice and upsampling it
# with bicubic interpolation.  This is ~40x faster than evaluating a
# sin()-based hash per texel and produces the same fractal look.
# --------------------------------------------------------------------------

_ATLAS_SHAPE = (2048, 4096)


def tileable_resize(lattice: np.ndarray, W: int, H: int, wrap_x: bool = True) -> np.ndarray:
    """Upsample a small random lattice to (H, W), seamlessly in the X axis."""
    h, w = lattice.shape
    if wrap_x:
        big = np.pad(lattice, ((0, 1), (0, 1)), mode="wrap")
        up = cv2.resize(big, (W + 1, H + 1), interpolation=cv2.INTER_CUBIC)[:H, :W]
    else:
        big = np.pad(lattice, ((0, 1), (0, 0)), mode="edge")
        up = cv2.resize(big, (W, H + 1), interpolation=cv2.INTER_CUBIC)[:H, :]
    return up.astype(np.float32)


def noise2d(shape, cycles_x: float, cycles_y: float, octaves: int = 4,
            seed: int = 0, gain: float = 0.5, lacunarity: float = 2.0,
            wrap_x: bool = True) -> np.ndarray:
    """
    Fractal value noise over an image of ``shape`` with the given number of
    noise cycles across each axis.  ``seed`` makes it fully reproducible.
    """
    H, W = shape
    rng = np.random.default_rng(int(seed) & 0x7FFFFFFF)
    total = np.zeros((H, W), dtype=np.float32)
    amp, norm = 1.0, 0.0
    fx, fy = max(cycles_x, 1.0), max(cycles_y, 1.0)
    for _ in range(max(1, octaves)):
        wl = max(2, int(round(fx * 2.0)))
        hl = max(2, int(round(fy * 2.0)))
        if wrap_x:
            wl = max(2, int(round(fx)))          # +1 column added by the pad
        if wl >= W // 2 or hl >= H // 2:
            # frequency is at/above the texel grid: pure random field
            total += amp * rng.random((H, W)).astype(np.float32)
        else:
            lat = rng.random((hl, wl)).astype(np.float32)
            total += amp * tileable_resize(lat, W, H, wrap_x=wrap_x)
        norm += amp
        amp *= gain
        fx *= lacunarity
        fy *= lacunarity
    return total / max(norm, 1e-9)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0 + 1e-12), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def polyline_distance(A, B, poly, margin: float = 8.0, already_windowed: bool = False):
    """
    Minimum distance from every (A, B) grid node to a polyline whose vertices
    are given in the *same units as A and B*, plus the normalised parameter
    along that polyline (used for taper control).

    Distances are returned in those units.  The search is restricted to the
    bounding box of the polyline grown by ``margin`` units, which is what
    keeps the ~8.4 megatexel atlas build in the low seconds.
    """
    H, W = A.shape
    va = np.asarray([p[0] for p in poly], dtype=np.float64)
    vb = np.asarray([p[1] for p in poly], dtype=np.float64)

    if already_windowed:
        # A/B are already cropped to the region of interest: use it all
        r0, c0, r1, c1 = 0, 0, H, W
    else:
        a0, a1 = va.min() - margin, va.max() + margin
        b0, b1 = vb.min() - margin, vb.max() + margin
        c0 = max(0, int(math.floor(a0)))       # A varies along the column axis
        c1 = min(W, int(math.ceil(a1)) + 2)
        r0 = max(0, int(math.floor(b0)))
        r1 = min(H, int(math.ceil(b1)) + 2)

    dist = np.full(A.shape, 1e6, dtype=np.float32)
    param = np.zeros(A.shape, dtype=np.float32)
    if c1 <= c0 or r1 <= r0:
        return dist, param

    aa = np.asarray(A[r0:r1, c0:c1], dtype=np.float32)
    bb = np.asarray(B[r0:r1, c0:c1], dtype=np.float32)
    d = np.full(aa.shape, 1e6, dtype=np.float32)
    pm = np.zeros(aa.shape, dtype=np.float32)
    n = max(len(poly) - 1, 1)
    for k in range(len(poly) - 1):
        ax, ay = float(va[k]), float(vb[k])
        dx, dy = float(va[k + 1] - va[k]), float(vb[k + 1] - vb[k])
        L2 = dx * dx + dy * dy + 1e-12
        t = np.clip(((aa - ax) * dx + (bb - ay) * dy) / L2, 0.0, 1.0)
        dk = np.sqrt((aa - (ax + t * dx)) ** 2 + (bb - (ay + t * dy)) ** 2)
        upd = dk < d
        d = np.where(upd, dk, d)
        pm = np.where(upd, (k + t) / n, pm)
    dist[r0:r1, c0:c1] = d
    param[r0:r1, c0:c1] = pm
    return dist, param


def bilinear_sample(img: np.ndarray, x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Bilinear sample of an (H, W, C) or (H, W) image at float pixel coords."""
    H, W = img.shape[:2]
    x = np.clip(x, 0, W - 1.001)
    y = np.clip(y, 0, H - 1.001)
    x0 = np.floor(x).astype(np.int32)
    y0 = np.floor(y).astype(np.int32)
    x1 = np.minimum(x0 + 1, W - 1)
    y1 = np.minimum(y0 + 1, H - 1)
    fx, fy = (x - x0), (y - y0)
    if img.ndim == 3:
        fx, fy = fx[..., None], fy[..., None]
    a = img[y0, x0].astype(np.float32)
    b = img[y0, x1].astype(np.float32)
    c = img[y1, x0].astype(np.float32)
    d = img[y1, x1].astype(np.float32)
    top = a + (b - a) * fx
    bot = c + (d - c) * fx
    return top + (bot - top) * fy


# ==========================================================================
# Procedural surface texture atlas (the "digital material" of the pier)
# ==========================================================================

ATLAS_W = 4096     # azimuth samples: 2*pi*R = 1.885 m of surface -> 0.46 mm/px
ATLAS_H = 2048     # elevation samples: 3.0 m -> 1.46 mm/px

SURF_W = 2.0 * math.pi * C.COLUMN_RADIUS_M   # 1.885 m of developed surface
SURF_H = C.COLUMN_HEIGHT_M                   # 3.0 m

class PierMaterial:
    """
    Cylindrical unwrap of the pier surface: smooth grey concrete with form
    seams, tie-rod holes, cold joints and weathering streaks -- plus the four
    structural defects composited on top with a realistic appearance.

    Channels produced (atlas resolution, float32 unless noted):
        albedo     (H, W, 3) diffuse colour 0..1
        roughness  (H, W)    1 = fully matte
        metal      (H, W)    bare-steel mask (exposed rebar)
        disp       (H, W)    out-of-plane displacement in metres (spall voids,
                             crack lips) -- fed to the 3D digital-twin mesh
        labels     (H, W)u8  ground-truth class index (0 = sound concrete)

    Every defect is painted inside a bounded window of the atlas, which keeps
    the ~8.4 megatexel build in the low seconds while retaining sub-millimetre
    crack detail.
    """

    def __init__(self, seed: int = 20261011):
        self.seed = int(seed)
        self.albedo: Optional[np.ndarray] = None
        self.roughness: Optional[np.ndarray] = None
        self.metal: Optional[np.ndarray] = None
        self.disp: Optional[np.ndarray] = None
        self.labels: Optional[np.ndarray] = None
        self.defect_layers: Dict[str, np.ndarray] = {}
        self.build_time_s: float = 0.0

    # ------------------------------------------------------------- windows
    @staticmethod
    def _window(theta0: float, theta1: float, y0: float, y1: float,
                margin_deg: float = 6.0, margin_m: float = 0.30):
        """
        Atlas pixel window (r0, r1, c0, c1) covering the given surface region
        expressed as an azimuth range (rad) and an elevation range (m), grown
        by the requested margins.
        """
        H, W = ATLAS_H, ATLAS_W
        t0 = min(theta0, theta1) - math.radians(margin_deg)
        t1 = max(theta0, theta1) + math.radians(margin_deg)
        c0 = int(math.floor((t0 / (2.0 * math.pi) + 0.5) * W - 0.5))
        c1 = int(math.ceil((t1 / (2.0 * math.pi) + 0.5) * W - 0.5))
        r0 = int(math.floor((1.0 - (max(y0, y1) + margin_m) / SURF_H) * H - 0.5))
        r1 = int(math.ceil((1.0 - (min(y0, y1) - margin_m) / SURF_H) * H - 0.5))
        # a region straddling the +/-pi seam is handled by clamping + wrap copy
        return (max(0, r0), min(H, r1), max(0, c0), min(W, c1))

    # ------------------------------------------------------------------ build
    def build(self) -> "PierMaterial":
        t0 = time.time()
        H, W = ATLAS_H, ATLAS_W
        sd = self.seed
        shape = (H, W)

        th = ((np.arange(W) + 0.5) / W) * 2.0 * math.pi - math.pi     # -pi..pi
        yy = (1.0 - (np.arange(H)[:, None] + 0.5) / H) * SURF_H
        S = np.broadcast_to(th[None, :] * C.COLUMN_RADIUS_M, shape).astype(np.float32)
        Y = np.broadcast_to(yy, shape).astype(np.float32)

        # --- base concrete -------------------------------------------------
        low = noise2d(shape, 4.1, 6.6, 4, sd + 1)
        mid = noise2d(shape, 26.0, 42.0, 3, sd + 2)
        micro = noise2d(shape, 360.0, 570.0, 2, sd + 3)
        grit = noise2d(shape, 1700.0, 2700.0, 1, sd + 4)

        base = (0.658 + 0.072 * (low - 0.5) + 0.040 * (mid - 0.5)
                + 0.024 * (micro - 0.5) + 0.032 * (grit - 0.5))
        albedo = np.stack([base * 1.006, base, base * 0.974], axis=-1).astype(np.float32)

        tint = noise2d(shape, 10.4, 16.5, 3, sd + 5) - 0.5
        albedo[..., 0] += 0.020 * tint
        albedo[..., 2] -= 0.016 * tint

        # --- formwork panel seams (three 120 deg panels) --------------------
        panel = SURF_W / 3.0
        dist_seam = np.abs(((S + panel / 2) % panel) - panel / 2)
        albedo *= (1.0 - 0.13 * (1.0 - smoothstep(0.0, 0.0055, dist_seam)))[..., None]

        # --- form tie-rod holes --------------------------------------------
        tie_x, tie_y = 0.30, 0.50
        gx = ((S + tie_x * 0.5 + 0.037) % tie_x) - tie_x * 0.5
        gy = ((Y + tie_y * 0.5) % tie_y) - tie_y * 0.5
        r_tie = np.sqrt(gx * gx + gy * gy)
        hole = 1.0 - smoothstep(0.010, 0.014, r_tie)
        hole_rim = np.clip((1.0 - smoothstep(0.014, 0.022, r_tie)) - hole, 0.0, 1.0)
        albedo *= (1.0 - 0.34 * hole - 0.07 * hole_rim)[..., None]

        # --- horizontal cold joints ----------------------------------------
        for jy, jstr in ((1.62, 0.24), (0.86, 0.12)):
            jl = 1.0 - smoothstep(0.0, 0.0042, np.abs(Y - jy))
            albedo *= (1.0 - jstr * jl)[..., None]

        # --- weathering / dirt runs / base grime ---------------------------
        albedo *= (1.0 - 0.22 * smoothstep(0.50, 0.78, noise2d(shape, 49.0, 0.8, 3, sd + 6)))[..., None]
        albedo *= (1.0 - smoothstep(0.42, 0.02, Y) * 0.22)[..., None]
        splash = smoothstep(0.16, 0.0, Y) * (0.35 + 0.35 * noise2d(shape, 226.0, 90.0, 2, sd + 7))
        albedo *= (1.0 - 0.22 * splash)[..., None]
        del low, mid, tint, dist_seam, gx, gy, r_tie, hole, hole_rim, splash

        roughness = np.clip(0.86 + 0.06 * (micro - 0.5), 0.55, 1.0).astype(np.float32)
        metal = np.zeros(shape, dtype=np.float32)
        disp = np.zeros(shape, dtype=np.float32)
        labels = np.zeros(shape, dtype=np.uint8)

        # --- composite the four structural defects --------------------------
        m_eff = self._efflorescence(S, Y, albedo, roughness)
        m_spall = self._spalling(S, Y, albedo, roughness, disp)
        m_corr, m_metal = self._corrosion(S, Y, albedo, roughness)
        metal = np.maximum(metal, m_metal).astype(np.float32)
        m_crack = self._defect_crack(S, Y, albedo, disp)

        for cls, mask in (("efflorescence", m_eff), ("spalling", m_spall),
                          ("corrosion", m_corr), ("crack", m_crack)):
            idx = C.DEFECT_CLASSES.index(cls) + 1
            labels[(mask > 0.35) & (labels == 0)] = idx

        self.albedo = np.clip(albedo, 0.0, 1.0)
        self.roughness = roughness
        self.metal = metal
        self.disp = disp
        self.labels = labels
        self.defect_layers = {
            "crack": m_crack > 0.35,
            "corrosion": m_corr > 0.35,
            "spalling": m_spall > 0.35,
            "efflorescence": m_eff > 0.35,
        }
        self.build_time_s = time.time() - t0
        return self

    # --------------------------------------------------------------- defects
    # ---- atlas pixel coordinate helpers (texel-accurate painting) ---------
    @staticmethod
    def _theta_y_to_px(theta_rad, y_m):
        """Surface (azimuth rad, elevation m) -> atlas pixel (col, row)."""
        col = ((theta_rad / (2.0 * math.pi)) + 0.5) * ATLAS_W - 0.5
        row = (1.0 - y_m / SURF_H) * ATLAS_H - 0.5
        return col, row

    def _defect_crack(self, S, Y, albedo, disp):
        """
        Diagonal 45 deg shear crack: tapering main limb, a real branch
        network, chipped lips and iron-oxide staining inside the crack.

        Painting happens in *atlas texel space* with a 1-texel anti-aliased
        footprint, so a 1.8-4.2 mm crack is drawn at the finest width the
        unwrap can represent instead of being lost between texels.
        """
        spec = C.DEFECTS_BY_ID["D-01"]
        ex = spec.extra
        H, W = ATLAS_H, ATLAS_W
        TEXEL_M = math.sqrt((SURF_W / W) * (SURF_H / H))     # ~0.82 mm

        # polyline + branches converted to atlas pixel coordinates
        def to_px(verts):
            return [self._theta_y_to_px(math.radians(d), y) for (d, y) in verts]

        poly_px = to_px(ex["poly"])
        brass = [to_px(b) for b in ex["branches"]]

        cs = [p[0] for p in poly_px] + [p[0] for b in brass for p in b]
        rs = [p[1] for p in poly_px] + [p[1] for b in brass for p in b]
        c0 = max(0, int(min(cs)) - 12)
        c1 = min(W, int(max(cs)) + 13)
        r0 = max(0, int(min(rs)) - 12)
        r1 = min(H, int(max(rs)) + 13)

        cc = np.broadcast_to(np.arange(W, dtype=np.float32)[None, :], (H, W))[r0:r1, c0:c1]
        rr_ = np.broadcast_to(np.arange(H, dtype=np.float32)[:, None], (H, W))[r0:r1, c0:c1]
        al_w = albedo[r0:r1, c0:c1]
        dp_w = disp[r0:r1, c0:c1]

        dist, param = polyline_distance(cc, rr_, poly_px, already_windowed=True)
        # crack does not run to the window edge
        inside = (dist < 1e5)
        dist = np.where(inside, dist, 1e6)

        w_mm = ex["width_mm"] + (ex["max_width_mm"] - ex["width_mm"]) * \
            np.clip(np.sin(np.pi * np.clip(param, 0.0, 1.0)), 0.0, 1.0) ** 0.7
        # half width in texels, never thinner than ~1.4 texels
        half_w = np.maximum(1.4, (w_mm / 1000.0) / TEXEL_M * 0.5).astype(np.float32)

        jitter = (noise2d((r1 - r0, c1 - c0), 40.0, 40.0, 2, self.seed + 21) - 0.5) * 1.6
        d_j = np.abs(dist + jitter)

        main = (1.0 - smoothstep(half_w * 0.55, half_w * 1.45, d_j)).astype(np.float32)
        for bpx in brass:
            d_b, _ = polyline_distance(cc, rr_, bpx, already_windowed=True)
            main = np.maximum(main, (1.0 - smoothstep(1.0, 2.6, d_b + jitter)).astype(np.float32))
        lip = np.clip((1.0 - smoothstep(half_w * 1.9, half_w * 5.0, d_j)) - main, 0.0, 1.0).astype(np.float32)

        # crack interior: deep shadow, warm iron-oxide staining
        al_w *= (1.0 - 0.87 * main)[..., None]
        al_w[..., 0] += 0.055 * main
        al_w[..., 1] += 0.014 * main
        # crack lips: chipped, exposed rough aggregate
        al_w *= (1.0 + 0.14 * lip)[..., None]
        al_w[..., 0] += 0.010 * lip

        # recess the opening (~1 crack width) into the digital-twin mesh
        dp_w -= ((w_mm / 1000.0) * 0.9 * main).astype(np.float32)
        dp_w += (0.0012 * lip).astype(np.float32)

        mask = np.zeros(S.shape, dtype=np.float32)
        mask[r0:r1, c0:c1] = np.clip(main + 0.5 * lip, 0.0, 1.0)
        return mask

    def _corrosion(self, S, Y, albedo, roughness):
        """
        Rebar corrosion: spalled cover zone, exposed section-loss rebar
        (shiny, ribbed, orange-brown) and rust bleeding that runs down the
        face under gravity.
        """
        spec = C.DEFECTS_BY_ID["D-02"]
        ex = spec.extra
        r0, r1, c0, c1 = self._window(spec.theta0, spec.theta1,
                                      spec.y0 - ex["stain_run_m"] - 0.20,
                                      spec.y1 + 0.15, margin_deg=5.0, margin_m=0.05)
        Sw, Yw = S[r0:r1, c0:c1], Y[r0:r1, c0:c1]
        al_w = albedo[r0:r1, c0:c1]
        ro_w = roughness[r0:r1, c0:c1]
        shape = Sw.shape

        th_c = spec.theta_mid * C.COLUMN_RADIUS_M
        half_w = 0.5 * (spec.theta1 - spec.theta0) * C.COLUMN_RADIUS_M
        y_c, half_h = spec.y_mid, 0.5 * (spec.y1 - spec.y0)

        wob = (noise2d(shape, 16.0, 26.0, 3, self.seed + 31) - 0.5) * 0.34
        rr = np.sqrt(((Sw - th_c) / half_w) ** 2 + ((Yw - y_c) / half_h) ** 2) + wob
        patch = (1.0 - smoothstep(0.72, 1.12, rr)).astype(np.float32)

        # --- rust-stained, fretted concrete inside the patch ----------------
        rust_amt = np.clip(patch * (0.45 + 0.55 * noise2d(shape, 38.0, 60.0, 4, self.seed + 32)),
                           0.0, 1.0).astype(np.float32)
        al_w[..., 0] = al_w[..., 0] * (1 - rust_amt) + 0.52 * rust_amt
        al_w[..., 1] = al_w[..., 1] * (1 - rust_amt) + 0.255 * rust_amt
        al_w[..., 2] = al_w[..., 2] * (1 - rust_amt) + 0.115 * rust_amt

        pit = smoothstep(0.70, 0.90, noise2d(shape, 280.0, 450.0, 1, self.seed + 33))
        al_w *= (1.0 - 0.45 * pit * patch)[..., None]

        # --- exposed reinforcement ------------------------------------------
        bar_th = ex["bar_theta_deg"] * math.pi / 180.0 * C.COLUMN_RADIUS_M
        bar_r = 0.014                                # D28 bar half-width
        bar_mask = np.zeros(shape, dtype=np.float32)
        for bar_y in (y_c - 0.26, y_c + 0.30):
            d_bar = np.sqrt(((Sw - th_c) / 1.35) ** 2 + (Yw - bar_y) ** 2)
            bar_mask = np.maximum(bar_mask, 1.0 - smoothstep(bar_r * 0.75, bar_r * 1.5, d_bar))
        d_v = np.abs(Sw - bar_th)
        v_bar = ((1.0 - smoothstep(bar_r * 0.8, bar_r * 1.55, d_v))
                 * smoothstep(spec.y0 - 0.04, spec.y0 + 0.10, Yw)
                 * smoothstep(spec.y1 + 0.04, spec.y1 - 0.10, Yw))
        bar_mask = (np.maximum(bar_mask, v_bar) * np.clip(patch * 1.6, 0.0, 1.0)).astype(np.float32)

        rib = 0.5 + 0.5 * np.cos(Yw * 210.0)
        steel = 0.30 + 0.16 * rib + 0.12 * noise2d(shape, 160.0, 260.0, 3, self.seed + 34)
        steel_rust = 0.55 + 0.25 * noise2d(shape, 86.0, 140.0, 3, self.seed + 35)
        mix = np.clip(0.35 + 0.65 * noise2d(shape, 48.0, 78.0, 3, self.seed + 36), 0, 1)

        bm = bar_mask
        for ch, s_v, r_v in ((0, 1.00, 1.00), (1, 0.82, 0.52), (2, 0.72, 0.22)):
            val = (steel * s_v * (1.0 - mix) + steel_rust * r_v * mix).astype(np.float32)
            al_w[..., ch] = np.where(bar_mask > 0.01, val * bm + al_w[..., ch] * (1 - bm), al_w[..., ch])
        ro_w[:] = np.where(bar_mask > 0.2, 0.42, ro_w).astype(np.float32)

        # --- rust bleed running down the face below the corrosion cell -------
        below = np.clip(Yw - spec.y0, 0.0, None)
        run = noise2d(shape, 18.0, 0.35, 3, self.seed + 37)
        bleed = (smoothstep(0.50, 0.82, run)
                 * np.exp(-below / max(ex["stain_run_m"], 0.1))
                 * smoothstep(spec.y1 + 0.06, spec.y1 - 0.25, Yw))
        bleed = np.clip(bleed * 1.15, 0.0, 1.0).astype(np.float32)
        al_w[..., 0] = al_w[..., 0] * (1 - bleed) + 0.46 * bleed
        al_w[..., 1] = al_w[..., 1] * (1 - bleed) + 0.30 * bleed
        al_w[..., 2] = al_w[..., 2] * (1 - bleed) + 0.20 * bleed

        # --- ground-truth label: the corroded cell plus the rust staining
        # that has run down the face (both are part of the corrosion defect) ---
        win_mask = np.clip(np.maximum(patch, bleed), 0.0, 1.0).astype(np.float32)

        mask = np.zeros(S.shape, dtype=np.float32)
        mask[r0:r1, c0:c1] = win_mask
        metal = np.zeros(S.shape, dtype=np.float32)
        metal[r0:r1, c0:c1] = bar_mask
        return mask, metal

    def _spalling(self, S, Y, albedo, roughness, disp):
        """
        Spalling / delamination: a deep irregular void with exposed coarse
        aggregate, a dark shadowed upper lip and a bright broken lower rim.
        """
        spec = C.DEFECTS_BY_ID["D-03"]
        r0, r1, c0, c1 = self._window(spec.theta0, spec.theta1, spec.y0, spec.y1,
                                      margin_deg=6.0, margin_m=0.20)
        Sw, Yw = S[r0:r1, c0:c1], Y[r0:r1, c0:c1]
        al_w = albedo[r0:r1, c0:c1]
        ro_w = roughness[r0:r1, c0:c1]
        dp_w = disp[r0:r1, c0:c1]
        shape = Sw.shape

        th_c, y_c = spec.theta_mid * C.COLUMN_RADIUS_M, spec.y_mid
        a = 0.5 * (spec.theta1 - spec.theta0) * C.COLUMN_RADIUS_M * 1.35
        b = 0.5 * (spec.y1 - spec.y0) * 1.30

        wob = (noise2d(shape, 12.0, 19.0, 3, self.seed + 41) - 0.5) * 0.30
        rr = np.sqrt(((Sw - th_c) / a) ** 2 + ((Yw - y_c) / b) ** 2) + wob
        void = (1.0 - smoothstep(0.80, 1.02, rr)).astype(np.float32)

        depth = spec.extra["depth_mm"] / 1000.0
        shadow = smoothstep(y_c + b * 0.9, y_c - b * 0.35, Yw)
        tone = (0.44 - 0.16 * shadow
                + 0.05 * noise2d(shape, 64.0, 100.0, 3, self.seed + 42)).astype(np.float32)
        al_w[..., 0] = al_w[..., 0] * (1 - void) + tone * 1.02 * void
        al_w[..., 1] = al_w[..., 1] * (1 - void) + tone * 1.00 * void
        al_w[..., 2] = al_w[..., 2] * (1 - void) + tone * 0.96 * void

        # exposed coarse aggregate: light limestone + dark basalt
        light_agg = smoothstep(0.74, 0.86, noise2d(shape, 140.0, 220.0, 1, self.seed + 43)) * void
        dark_agg = smoothstep(0.72, 0.84, noise2d(shape, 176.0, 278.0, 1, self.seed + 44)) * void
        al_w[..., 0] += 0.30 * light_agg - 0.22 * dark_agg
        al_w[..., 1] += 0.29 * light_agg - 0.23 * dark_agg
        al_w[..., 2] += 0.27 * light_agg - 0.24 * dark_agg

        # broken rim + a fine delamination halo around the void
        rim = np.clip((1.0 - smoothstep(0.98, 1.10, rr)) - void, 0.0, 1.0)
        wob2 = (noise2d(shape, 48.0, 76.0, 3, self.seed + 45) - 0.5) * 0.15
        halo = np.clip((1.0 - smoothstep(1.05, 1.22, rr + wob2)) - void - rim, 0.0, 1.0)
        al_w *= (1.0 + 0.16 * rim)[..., None]
        al_w *= (1.0 - 0.18 * halo)[..., None]

        ro_w[:] = np.where(void > 0.4, 0.95, ro_w).astype(np.float32)
        # the void is a real depression in the 3D surface
        dp_w -= (depth * void).astype(np.float32)

        mask = np.zeros(S.shape, dtype=np.float32)
        mask[r0:r1, c0:c1] = np.clip(np.maximum(void, halo * 0.6), 0.0, 1.0)
        return mask

    def _efflorescence(self, S, Y, albedo, roughness):
        """
        Efflorescence / moisture seepage: cloudy white calcium-carbonate bloom
        with soft edges and vertical drip runs, worst near the base.
        """
        spec = C.DEFECTS_BY_ID["D-04"]
        r0, r1, c0, c1 = self._window(spec.theta0, spec.theta1, spec.y0 - 0.45, spec.y1,
                                      margin_deg=6.0, margin_m=0.10)
        Sw, Yw = S[r0:r1, c0:c1], Y[r0:r1, c0:c1]
        al_w = albedo[r0:r1, c0:c1]
        ro_w = roughness[r0:r1, c0:c1]
        shape = Sw.shape

        th_c, y_c = spec.theta_mid * C.COLUMN_RADIUS_M, spec.y_mid
        a = 0.5 * (spec.theta1 - spec.theta0) * C.COLUMN_RADIUS_M * 1.5
        b = 0.5 * (spec.y1 - spec.y0) * 1.6

        wob = (noise2d(shape, 10.0, 16.0, 4, self.seed + 51) - 0.5) * 0.55
        rr = np.sqrt(((Sw - th_c) / a) ** 2 + ((Yw - y_c) / b) ** 2) + wob
        bloom = 1.0 - smoothstep(0.55, 1.25, rr)

        amt = np.clip(bloom * (0.55 + 0.45 * noise2d(shape, 26.0, 41.0, 4, self.seed + 52)) * 1.35,
                      0.0, 1.0)
        drip = smoothstep(0.72, 0.93, noise2d(shape, 40.0, 0.6, 2, self.seed + 53))
        below = np.clip(Yw - spec.y0, 0.0, None)
        drip_amt = np.clip(drip * np.exp(-below / 0.42) * 0.75, 0.0, 1.0)

        tot = np.clip(amt + drip_amt, 0.0, 1.0).astype(np.float32)
        al_w[..., 0] = al_w[..., 0] * (1 - tot) + 0.905 * tot
        al_w[..., 1] = al_w[..., 1] * (1 - tot) + 0.912 * tot
        al_w[..., 2] = al_w[..., 2] * (1 - tot) + 0.885 * tot
        ro_w[:] = np.where(tot > 0.3, 0.97, ro_w).astype(np.float32)

        mask = np.zeros(S.shape, dtype=np.float32)
        mask[r0:r1, c0:c1] = tot
        return mask


